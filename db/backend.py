import os
import shutil
import sqlite3
import sys
from typing import List

_USE_SQLITE_FALLBACK = False


def get_database_url() -> str:
    return (os.getenv("DATABASE_URL") or "").strip().strip("'\"")


DATABASE_URL = get_database_url()


def is_testing() -> bool:
    return bool(
        "pytest" in sys.modules
        or any("pytest" in arg for arg in sys.argv)
        or os.getenv("PYTEST_CURRENT_TEST")
        or os.getenv("TESTING", "").lower() in ("1", "true", "yes")
        or os.getenv("SQLITE_PATH")
    )


def get_sqlite_path() -> str:
    custom_path = (os.getenv("SQLITE_PATH") or "").strip()
    if custom_path:
        return custom_path
    base_db = os.path.join(os.path.dirname(os.path.abspath(__file__)), "bookings.db")
    if os.getenv("VERCEL") or os.getenv("AWS_LAMBDA_FUNCTION_NAME"):
        tmp_path = "/tmp/bookings.db"
        if not os.path.exists(tmp_path):
            if os.path.exists(base_db):
                try:
                    shutil.copy2(base_db, tmp_path)
                except Exception:
                    pass
        return tmp_path
    if os.path.exists(base_db):
        return base_db
    return "db/bookings.db"


SQLITE_PATH = get_sqlite_path()


def is_postgres() -> bool:
    if is_testing():
        return False
    db_url = get_database_url()
    return bool(
        db_url and (db_url.startswith("postgresql://") or db_url.startswith("postgres://"))
    )


def get_conn():
    if is_testing():
        return sqlite3.connect(get_sqlite_path(), check_same_thread=False)

    if not is_postgres():
        raise RuntimeError(
            "PostgreSQL is required for runtime, but DATABASE_URL is not set or invalid. "
            "Please check your PostgreSQL configuration."
        )

    import psycopg  # type: ignore

    connect_timeout = int((os.getenv("PG_CONNECT_TIMEOUT") or "5").strip() or "5")

    # Disable prepared statements to avoid PgBouncer/Supabase
    # transaction-pool errors like:
    # DuplicatePreparedStatement: prepared statement "_pg3_0" already exists
    return psycopg.connect(
        get_database_url(),
        prepare_threshold=None,
        connect_timeout=max(2, connect_timeout),
    )


def adapt_query(query: str) -> str:
    if is_postgres():
        return query.replace("?", "%s")
    return query


def execute(cur, query: str, params=None):
    if params is None:
        return cur.execute(adapt_query(query))
    return cur.execute(adapt_query(query), params)


def executemany(cur, query: str, params_list):
    return cur.executemany(adapt_query(query), params_list)


def id_pk_col() -> str:
    if is_postgres():
        return "BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY"
    return "INTEGER PRIMARY KEY AUTOINCREMENT"


def list_columns(conn, table: str) -> List[str]:
    if is_postgres():
        with conn.cursor() as cur:
            cur.execute(
                """
                SELECT column_name
                FROM information_schema.columns
                WHERE table_schema='public' AND table_name=%s
                """,
                (table,),
            )
            return [r[0] for r in cur.fetchall()]
    cur = conn.cursor()
    cur.execute(f"PRAGMA table_info({table})")
    return [r[1] for r in cur.fetchall()]


def ensure_column(conn, table: str, column: str, col_type_sql: str):
    cols = list_columns(conn, table)
    if column in cols:
        return
    cur = conn.cursor()
    if is_postgres():
        cur.execute(f'ALTER TABLE "{table}" ADD COLUMN IF NOT EXISTS "{column}" {col_type_sql}')
    else:
        cur.execute(f"ALTER TABLE {table} ADD COLUMN {column} {col_type_sql}")
    conn.commit()
